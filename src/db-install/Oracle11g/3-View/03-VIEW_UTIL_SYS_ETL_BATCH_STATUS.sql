CREATE OR REPLACE VIEW {Schema}.VIEW_UTIL_SYS_ETL_BATCH_STATUS AS
WITH UNFINISHED_TASKS AS (
    SELECT      t.BATCH_ID,
                COUNT(t.TASK_ID)    AS OUTSTANDING_TASKS
    FROM        {Schema}.UTIL_SYS_ETL_TASK_QUEUE t
    WHERE       t.COMPLETED_TIME    IS NULL
    GROUP BY    t.BATCH_ID
)
SELECT
    b.BATCH_ID,
    b.BATCH_STATUS,
    b.TASKS_COUNT,
    b.SCHEDULED_TIME,
    b.BATCH_COMMENT,
    b.ENTRY_TIME,
    b.TRIGGERED_TIME,
    NULL                            AS COMPLETED_TIME,
    CAST(SYSTIMESTAMP - NVL(b.TRIGGERED_TIME, SYSTIMESTAMP) AS INTERVAL DAY(1) TO SECOND(0))            AS TIME_ELAPSED,
    NVL(u.OUTSTANDING_TASKS, 0)     AS OUTSTANDING_TASKS,
    b.PARENT_BATCH_ID
FROM
    {Schema}.UTIL_SYS_ETL_BATCH_STATUS   b
    LEFT JOIN UNFINISHED_TASKS      u
    ON (u.BATCH_ID = b.BATCH_ID)

UNION ALL

SELECT
    h.BATCH_ID,
    h.BATCH_STATUS,
    h.TASKS_COUNT,
    h.SCHEDULED_TIME,
    h.BATCH_COMMENT,
    h.ENTRY_TIME,
    h.TRIGGERED_TIME,
    h.COMPLETED_TIME,
    CAST(NUMTODSINTERVAL(h.COMPLETED_TIME - h.TRIGGERED_TIME, 'DAY') AS INTERVAL DAY(1) TO SECOND(0))   AS TIME_ELAPSED,
    0                                                                                                   AS OUTSTANDING_TASKS,
    h.PARENT_BATCH_ID
FROM
    {Schema}.UTIL_SYS_ETL_BATCH_STATUS_HIST   h

WITH READ ONLY;
