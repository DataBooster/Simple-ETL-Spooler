CREATE OR REPLACE VIEW EDS.VIEW_UTIL_SYS_RFSH_TABLE_LOG AS
SELECT
    t.LOG_ID,
    t.RECEIVED_TIME,
    t.PAYLOAD_JSON,
    t.TARGET_TABLE,
    t.REFRESH_BY_DICT,
    t.UPDATE_COLUMNS,
    t.DELETE_SCRIPT,
    t.DELETED_ROWS,
    t.INSERT_SCRIPT,
    t.INSERTED_ROWS,
    t.ERROR_MSG,
    t.UPDATED_TIME,
    CAST(t.UPDATED_TIME - t.RECEIVED_TIME AS INTERVAL DAY(1) TO SECOND(3))  AS SPENT_TIME
FROM
    EDS.UTIL_SYS_RFSH_TABLE_LOG       t

UNION ALL

SELECT
    h.LOG_ID,
    h.RECEIVED_TIME,
    h.PAYLOAD_JSON,
    h.TARGET_TABLE,
    h.REFRESH_BY_DICT,
    h.UPDATE_COLUMNS,
    h.DELETE_SCRIPT,
    h.DELETED_ROWS,
    h.INSERT_SCRIPT,
    h.INSERTED_ROWS,
    h.ERROR_MSG,
    h.UPDATED_TIME,
    CAST(h.UPDATED_TIME - h.RECEIVED_TIME AS INTERVAL DAY(1) TO SECOND(3))  AS SPENT_TIME
FROM
    EDS.UTIL_SYS_RFSH_TABLE_LOG_HIST  h

WITH READ ONLY;

GRANT SELECT ON EDS.VIEW_UTIL_SYS_RFSH_TABLE_LOG TO OTPP_NON_PUBLIC;
