BEGIN
    EXECUTE IMMEDIATE 'DROP TABLE EDS.UTIL_SYS_RFSH_TABLE_LOG_HIST';
EXCEPTION
    WHEN OTHERS THEN
        NULL;
END;
/

CREATE TABLE EDS.UTIL_SYS_RFSH_TABLE_LOG_HIST
(
    LOG_ID            NUMBER(10, 0) NOT NULL,
    RECEIVED_TIME     TIMESTAMP(3)  NOT NULL,
    PAYLOAD_JSON      CLOB,
    TARGET_TABLE      VARCHAR2(100),
    REFRESH_BY_DICT   VARCHAR2(4000),
    UPDATE_COLUMNS    NUMBER(3, 0),
    DELETE_SCRIPT     VARCHAR2(4000),
    DELETED_ROWS      NUMBER(9, 0),
    INSERT_SCRIPT     CLOB,
    INSERTED_ROWS     NUMBER(9, 0),
    ERROR_MSG         VARCHAR2(4000),
    UPDATED_TIME      TIMESTAMP(3),
    CONSTRAINT PK_UTIL_SYS_RFSH_TABLE_LOG_HIS PRIMARY KEY (LOG_ID)
) ROW STORE COMPRESS ADVANCED NOLOGGING
STORAGE
(
  INITIAL 32M
  NEXT 32M
);

GRANT SELECT ON EDS.UTIL_SYS_RFSH_TABLE_LOG_HIST TO OTPP_NON_PUBLIC;
