BEGIN
    EXECUTE IMMEDIATE 'DROP TABLE EDS.UTIL_SYS_RFSH_TABLE_LOG';
EXCEPTION
    WHEN OTHERS THEN
        NULL;
END;
/

CREATE TABLE EDS.UTIL_SYS_RFSH_TABLE_LOG
(
    LOG_ID            NUMBER(10, 0) DEFAULT EDS.LOG_ID_SEQUENCE.NEXTVAL NOT NULL,
    RECEIVED_TIME     TIMESTAMP(3)  DEFAULT SYSTIMESTAMP  NOT NULL,
    PAYLOAD_JSON      CLOB,
    TARGET_TABLE      VARCHAR2(100),
    REFRESH_BY_DICT   VARCHAR2(4000),
    UPDATE_COLUMNS    NUMBER(3, 0),
    DELETE_SCRIPT     VARCHAR2(4000),
    DELETED_ROWS      NUMBER(9, 0),
    INSERT_SCRIPT     CLOB,
    INSERTED_ROWS     NUMBER(9, 0),
    ERROR_MSG         VARCHAR2(4000),
    UPDATED_TIME      TIMESTAMP(3),
    CONSTRAINT PK_UTIL_SYS_RFSH_TABLE_LOG PRIMARY KEY (LOG_ID)
) NOLOGGING
STORAGE
(
  INITIAL 1M
  NEXT 16M
);

GRANT SELECT ON EDS.UTIL_SYS_RFSH_TABLE_LOG TO OTPP_NON_PUBLIC;
