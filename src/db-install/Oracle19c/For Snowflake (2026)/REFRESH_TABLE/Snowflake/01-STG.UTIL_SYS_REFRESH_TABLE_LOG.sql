CREATE OR REPLACE SEQUENCE STG.UTIL_SYS_REFRESH_LOG_ID_SEQUENCE;

CREATE OR REPLACE HYBRID TABLE STG.UTIL_SYS_REFRESH_TABLE_LOG
(
    LOG_ID            NUMBER(10, 0) DEFAULT STG.UTIL_SYS_REFRESH_LOG_ID_SEQUENCE.NEXTVAL NOT NULL,
    RECEIVED_TIME     TIMESTAMP_NTZ(3) DEFAULT CAST(CURRENT_TIMESTAMP() AS TIMESTAMP_NTZ(3)) NOT NULL,
    PAYLOAD_JSON      STRING,
    TARGET_TABLE      VARCHAR(100),
    REFRESH_BY_DICT   VARIANT,
    UPDATE_COLUMNS    NUMBER(3, 0),
    DELETE_SCRIPT     VARCHAR(4000),
    DELETED_ROWS      NUMBER(9, 0),
    INSERT_SCRIPT     STRING,
    INSERTED_ROWS     NUMBER(9, 0),
    ERROR_MSG         VARCHAR,
    UPDATED_TIME      TIMESTAMP_NTZ(3),
    SPENT_TIME        INTERVAL HOUR(2) TO SECOND(3)  AS ((UPDATED_TIME - RECEIVED_TIME)::INTERVAL HOUR(2) TO SECOND(3)),

    CONSTRAINT PK_UTIL_SYS_REFRESH_TABLE_LOG PRIMARY KEY (LOG_ID)
);
