BEGIN
    EXECUTE IMMEDIATE 'DROP TABLE EDS.DAILY_RFSH_TO_SF_TASK_CONF';
EXCEPTION
    WHEN OTHERS THEN
        NULL;
END;
/

-- Create table
CREATE TABLE EDS.DAILY_RFSH_TO_SF_TASK_CONF
(
    TARGET_TABLE      VARCHAR2(80)      NOT NULL,
    SOURCE_QUERY      VARCHAR2(4000)    NOT NULL,
    DATE_COLUMN       VARCHAR2(50),
    SUBJECT_AREA      VARCHAR2(16) DEFAULT 'DEFAULT' NOT NULL,
    REFRESH_ORDER     VARCHAR2(3) DEFAULT '000' NOT NULL,
    IS_ENABLED        CHAR(1)     DEFAULT 'Y'   NOT NULL,
    COMMENT_          VARCHAR2(200),

    CONSTRAINT PK_DAILY_RFSH_TO_SF_TASK_CONF PRIMARY KEY (TARGET_TABLE),
    CONSTRAINT CK_DAILY_RFSH_TO_SF_TARGET check (TARGET_TABLE = UPPER(TARGET_TABLE) AND REGEXP_LIKE(TARGET_TABLE, '^(\w+\.)?\w+$')),
    CONSTRAINT CK_DAILY_RFSH_TO_SF_DATE_COL check (DATE_COLUMN IS NULL OR REGEXP_LIKE(DATE_COLUMN, '^\w+$')),
    CONSTRAINT CK_DAILY_RFSH_TO_SF_ENABLE check (IS_ENABLED IN ('Y', 'N')),
    CONSTRAINT CK_DAILY_RFSH_TO_SF_QUERY check (REGEXP_LIKE(SOURCE_QUERY, '^[[:space:]]*(WITH[[:space:]]+[[:alnum:]_]+[[:space:]]+AS[[:space:]]*\(.*\)[[:space:]]*)?SELECT([[:space:]]*[^[:alnum:]_[:space:]]|[^[:alnum:]_].*[^[:space:]][^[:alnum:]_])FROM[^[:alnum:]_].*[^;[:space:]][[:space:]]*$', 'in'))
)   NOLOGGING;

COMMENT ON TABLE EDS.DAILY_RFSH_TO_SF_TASK_CONF IS 'Tasks config for daily refreshing Snowflake table from EDB table/view/select query';

CREATE INDEX EDS.IX_DAILY_RFSH_TO_SF_TASK_CONF ON EDS.DAILY_RFSH_TO_SF_TASK_CONF (IS_ENABLED, SUBJECT_AREA, REFRESH_ORDER);

GRANT SELECT ON EDS.DAILY_RFSH_TO_SF_TASK_CONF TO OTPP_USER_RISK2;
GRANT SELECT ON EDS.DAILY_RFSH_TO_SF_TASK_CONF TO OTPP_NON_PUBLIC;
