CREATE OR REPLACE VIEW EDS.VIEW_DAILY_RFSH_TASK_CONF AS
SELECT
    'Snowflake --> Oracle'  AS REFRESH_DIRECTION,
    ES.SOURCE_QUERY,
    ES.TARGET_TABLE,
    ES.DATE_COLUMN,
    ES.SUBJECT_AREA,
    ES.REFRESH_ORDER,
    ES.IS_ENABLED,
    ES.COMMENT_
FROM
    EDS.DAILY_RFSH_FROM_SF_TASK_CONF  ES

UNION ALL

SELECT
    'Oracle --> Snowflake'  AS REFRESH_DIRECTION,
    SE.SOURCE_QUERY,
    SE.TARGET_TABLE,
    SE.DATE_COLUMN,
    SE.SUBJECT_AREA,
    SE.REFRESH_ORDER,
    SE.IS_ENABLED,
    SE.COMMENT_
FROM
    EDS.DAILY_RFSH_TO_SF_TASK_CONF    SE

ORDER BY
    REFRESH_DIRECTION DESC,
    IS_ENABLED DESC,
    SUBJECT_AREA,
    REFRESH_ORDER

WITH READ ONLY;

GRANT SELECT ON EDS.VIEW_DAILY_RFSH_TASK_CONF TO OTPP_NON_PUBLIC;
