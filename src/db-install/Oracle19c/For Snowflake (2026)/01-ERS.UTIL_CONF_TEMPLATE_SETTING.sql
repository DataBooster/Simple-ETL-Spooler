BEGIN
    EXECUTE IMMEDIATE 'DROP TABLE ERS.UTIL_CONF_TEMPLATE_SETTING';
EXCEPTION
    WHEN OTHERS THEN
        NULL;
END;
/

CREATE TABLE ERS.UTIL_CONF_TEMPLATE_SETTING
(
    TEMPLATE_KEY        VARCHAR2(64)    NOT NULL,
    TEMPLATE_TEXT       VARCHAR2(4000)  NOT NULL,
    COMMENT_            VARCHAR2(1000),

    CONSTRAINT PK_UTIL_CONF_TEMPLATE_SETTING PRIMARY KEY (TEMPLATE_KEY),
    CONSTRAINT CK_UTIL_CONF_TEMPLATE_ITEM_KEY CHECK (TEMPLATE_KEY = UPPER(TRIM(TEMPLATE_KEY))),
    CONSTRAINT CK_UTIL_CONF_TEMPLATE_ITEM_TXT CHECK ((REGEXP_LIKE(TEMPLATE_TEXT, '^\s*(\{.*\}|\[.*\])\s*$') AND TEMPLATE_TEXT IS JSON) OR NOT REGEXP_LIKE(TEMPLATE_TEXT, '^\s*(\{.*\}|\[.*\])\s*$'))
)ORGANIZATION INDEX
INCLUDING TEMPLATE_TEXT
OVERFLOW TABLESPACE ERS;

GRANT SELECT ON ERS.UTIL_CONF_TEMPLATE_SETTING TO OTPP_APP_RISK2;
GRANT SELECT ON ERS.UTIL_CONF_TEMPLATE_SETTING TO OTPP_NON_PUBLIC;
